import string
import secrets


def generate_short_uuid() -> str:
    """
    Generates a bespoke, obfuscated Session ID using Base62.
    Format looks somewhat like a shortened IPv6 address: xxx:xxx:xxx
    e.g., a7F:b92:C4d. Reduces string bloat while retaining high entropy.
    """
    alphabet = string.ascii_letters + string.digits
    
    def get_chunk(length: int = 3) -> str:
        return ''.join(secrets.choice(alphabet) for _ in range(length))
        
    return f"{get_chunk()}:{get_chunk()}:{get_chunk()}"
